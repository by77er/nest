#!/usr/bin/env python3
"""Builds the M3' measurement's Rust crate from nestd's own source at a git revision, so the run
measures the shipped cut, not a copy of it: `nestd_core::shadow` (minus its tests and proofs), and,
verbatim, `storage.rs`'s map reads and clones and `host.rs`'s `pre_copy` and `cut_shadow` with their
helpers. Only paths, `tracing` and the stand-ins a real XFS never calls are shimmed.

    python3 -I dev/measure-cut/extract-cut.py <rev> <out dir>

The out dir gets `Cargo.toml` and `src/cut.rs`; `m3-nestd.rs` (beside this script) is the driver.
"""
import pathlib
import re
import subprocess
import sys

rev, out = sys.argv[1], pathlib.Path(sys.argv[2])
show = lambda p: subprocess.run(["git", "show", f"{rev}:{p}"], capture_output=True, text=True, check=True).stdout


def item(src, head):
    """The item whose first line starts with `head`, with its doc comments, to its closing brace."""
    m = re.search(rf"(?m)^((?:///.*\n)*){re.escape(head)}", src)
    if not m:
        sys.exit(f"{head!r} not found at {rev}")
    i, depth = src.index("{", m.end()), 0
    for j in range(i, len(src)):
        depth += {"{": 1, "}": -1}.get(src[j], 0)
        if depth == 0:
            return src[m.start():j + 1] + "\n"
    sys.exit(f"{head!r} unbalanced")


core = show("crates/nestd-core/src/shadow.rs")
core = core[:core.index("#[cfg(test)]")].replace("use alloc::vec::Vec;", "")
storage = show("crates/nestd/src/storage.rs")
host = show("crates/nestd/src/host.rs")
parts = [
    "// Generated by dev/measure-cut/extract-cut.py from nestd at " + rev + ". Do not edit.\n",
    "#![allow(dead_code, unused_imports, unused_variables, clippy::all)]\n",
    "use std::path::{Path, PathBuf};\nuse std::time::Instant;\n",
    "pub mod nestd_core { pub mod shadow {\n" + core + "\n} }\n",
    "use nestd_core::shadow as shadow_core;\n",
    "macro_rules! no_log { ($($t:tt)*) => {} }\n",
    "#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum CutMode { Shadow, SimShadow }\n",
    "pub mod storage {\nuse std::fs::{self, File, OpenOptions};\nuse std::io::{self, Read};\nuse std::os::fd::AsRawFd;\nuse std::os::unix::fs::FileExt;\nuse std::path::Path;\nuse super::nestd_core;\n",
]
for h in ["pub fn reflink(", "pub fn fiemap(", "pub fn clone_ranges(", "pub fn same_bytes(", "pub fn sync_data("]:
    parts.append(item(storage, h))
parts.append("pub fn sim_fiemap(_: &Path) -> io::Result<Vec<nestd_core::shadow::Extent>> { unreachable!() }\n"
             "pub fn sim_clone_ranges(_: &Path, _: &Path, _: &[nestd_core::shadow::Range]) -> io::Result<()> { unreachable!() }\n"
             "pub fn locked_copy(_: &Path, _: &Path) -> io::Result<()> { unreachable!() }\n}\n")
for h in ["struct PreCopy", "struct ShadowCut", "fn shadow_map(", "fn shadow_clone(", "fn shadow_whole(", "fn pre_copy(", "fn cut_shadow("]:
    text = item(host, h)
    # The driver reads their fields and calls them: public, nothing else changed.
    text = re.sub(r"(?m)^(struct |fn )", r"pub \1", text)
    text = re.sub(r"(?m)^(    )(\w+: )", r"\1pub \2", text) if h.startswith("struct") else text
    parts.append(re.sub(r"tracing::(warn|error|info)!", "no_log!", text))
(out / "src").mkdir(parents=True, exist_ok=True)
src = "".join(parts)
src = "\n".join(l for l in src.splitlines() if not l.lstrip().startswith("//") or l.startswith("// Generated")) + "\n"
(out / "src/cut.rs").write_text(src)
(out / "Cargo.toml").write_text('[package]\nname = "m3-nestd"\nversion = "0.0.0"\nedition = "2024"\n\n[[bin]]\nname = "m3-nestd"\npath = "src/main.rs"\n\n'
                                '[dependencies]\nlibc = "=0.2.190"\n\n[profile.release]\ndebug = false\n')
